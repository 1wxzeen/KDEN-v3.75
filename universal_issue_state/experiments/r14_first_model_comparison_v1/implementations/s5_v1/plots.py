"""Standalone scientific figures. Run in the separate reporting environment."""
from pathlib import Path
import json,sys
import numpy as np
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
P=Path(sys.argv[1]);F=P/'figures';F.mkdir(exist_ok=True)
load=lambda name:json.loads((P/name).read_text())
S=load('scorecards.json');C=load('calibration.json');SEL=load('selection.json');H=load('histograms.json');I=load('paired_inference.json');G=load('gam_effects.json');CA=load('cases.json')
MODELS=list(S);names={'B0_H':'Hourly baseline','B0_Q':'Subhourly baseline','ANEN':'AnEn','GAM_LS_NORMAL':'Location–scale GAM','GAM_LOCATION_NORMAL':'Constant-scale GAM','GAM_LS_T5':'Student-t GAM'}
colors=dict(zip(MODELS,['#777777','#222222','#2474a4','#d47722','#9774ad','#378365']))
plt.rcParams.update({'font.size':10,'axes.spines.top':False,'axes.spines.right':False,'figure.dpi':120,'savefig.dpi':150})
files=[]
def finish(fig,name,title):
 fig.suptitle(title);fig.tight_layout(rect=(0,0,1,.97));fig.savefig(F/(name+'.png'),bbox_inches='tight');plt.close(fig);files.append(name+'.png')

fig,axes=plt.subplots(1,3,figsize=(13,4))
for ax,key,label,scale in zip(axes,['mae','modal_integer_hit','negative_log_score'],['MAE (°F), lower better','Exact integer hit (%), higher better','Negative log score (nats), lower better'],[1,100,1]):
 vals=[S[m]['overall']['ALL']['metrics'][key]*scale for m in MODELS];cis=[S[m]['overall']['ALL']['intervals'][key] for m in MODELS]
 ax.barh(range(len(MODELS)),vals,color=[colors[m] for m in MODELS]);ax.errorbar(vals,range(len(MODELS)),xerr=[[max(0,vals[i]-c['lower']*scale) for i,c in enumerate(cis)],[max(0,c['upper']*scale-vals[i]) for i,c in enumerate(cis)]],fmt='none',color='black',capsize=2)
 ax.set_yticks(range(len(MODELS)),[names[m] for m in MODELS]);ax.invert_yaxis();ax.set_xlabel(label)
finish(fig,'overall_scorecard','980 days · identical support · descriptive 95% seven-day block intervals')
fig,ax=plt.subplots(figsize=(9,4));records=I['results']['7']
for i,r in enumerate(records):
 ci=r['familywise_interval'];ax.plot([ci['lower'],ci['upper']],[i,i],color='#2474a4');ax.scatter([r['difference']],[i],color='#2474a4')
ax.axvline(0,color='gray',linestyle='--');ax.set_yticks(range(len(records)),[names[r['model']]+' − '+names[r['reference']] for r in records]);ax.invert_yaxis();ax.set_xlabel('Difference in negative log score (negative favors first model)')
finish(fig,'paired_nll','Five registered contrasts · Bonferroni-adjusted bootstrap intervals · timing caveat applies')

fig,axes=plt.subplots(len(MODELS),2,figsize=(12,2.15*len(MODELS)))
for i,m in enumerate(MODELS):
 # Fold/issue values from a dedicated cross-tab generated by the scoring runner.
 tab=load('fold_issue.json')[m]
 for j,key in enumerate(['modal_integer_hit','calibration_gap']):
  values=np.array([[tab[oid][t][key] for t in sorted(tab[oid])] for oid in ['OUTER_01','OUTER_02','OUTER_03']])*100
  im=axes[i,j].imshow(values,aspect='auto',origin='upper',cmap='viridis' if j==0 else 'coolwarm',vmin=0 if j==0 else -15,vmax=40 if j==0 else 15)
  axes[i,j].set_yticks([0,1,2],['2023','2024','2025*']);axes[i,j].set_xticks([0,16,32,48,56],['02','06','10','14','16']);axes[i,j].set_xlabel('Denver issue hour');axes[i,j].set_title(names[m]+(' · exact hit %' if j==0 else ' · observed − predicted pp'));fig.colorbar(im,ax=axes[i,j],shrink=.8)
finish(fig,'fold_issue_heatmaps','Fold × issue: skill and calibration · *2025 through September 6')

for event in ['integer','pair_even','pair_odd','five_degree']:
 fig,axes=plt.subplots(2,3,figsize=(12,7))
 for ax,m in zip(axes.flat,MODELS):
  bins=C[m]['overall/ALL'][event]['bins'];valid=[b for b in bins if b['rows']]
  ax.plot([0,1],[0,1],color='gray',linestyle='--');ax.scatter([b['predicted'] for b in valid],[b['observed'] for b in valid],s=[20+180*b['weight'] for b in valid],color=colors[m])
  for b in valid:
   ci=b['observed_interval']
   if ci['lower'] is not None:ax.plot([b['predicted']]*2,[ci['lower'],ci['upper']],color=colors[m],alpha=.6)
  ax.set(xlim=(0,1),ylim=(0,1),xlabel='Mean predicted probability',ylabel='Observed frequency',title=names[m])
 finish(fig,'reliability_'+event,event+' reliability · area ∝ checkpoint coverage · diagnostic partitions are not Kalshi listings')
fig,axes=plt.subplots(2,3,figsize=(12,6))
for ax,m in zip(axes.flat,MODELS):
 b=C[m]['overall/ALL']['integer']['bins'];ax.bar([x['lower']+.05 for x in b],[x['weight']*100 for x in b],width=.09,color=colors[m]);ax.set(title=names[m],xlabel='Native maximum integer probability',ylabel='Day-weighted checkpoint share (%)',xlim=(0,1))
finish(fig,'confidence_histograms','Confidence support · bins fixed before evaluation')

for ranking in ['integer','pair_even','pair_odd','five_degree','negative_entropy','negative_width80']:
 fig,axes=plt.subplots(1,3,figsize=(13,4))
 for m in MODELS:
  rows=[r for r in SEL[m] if r['ranking']==ranking and r['slice']=='overall/ALL'];rows=sorted(rows,key=lambda r:r['dayweighted_coverage'])
  for ax,key,label in zip(axes,['event_hit','negative_log_score','discrete_crps_f'],['Selected hit rate','Selected log loss','Selected CRPS (°F)']):
   x=[100*r['dayweighted_coverage'] for r in rows];y=[r['metrics'][key] for r in rows];ax.plot(x,y,'o-',label=names[m],color=colors[m]);ax.set(xlabel='Actual day-weighted checkpoint coverage (%)',ylabel=label)
 axes[0].legend(fontsize=8)
 finish(fig,'selection_'+ranking,'Training-derived thresholds · '+ranking+' ranking · no outer cutoff optimization')
fig,axes=plt.subplots(1,2,figsize=(10,4))
for m in MODELS:
 o=S[m]['overall']['ALL']['metrics'];axes[0].plot([50,80,90,95],[100*o[f'interval_{l}_coverage'] for l in [50,80,90,95]],'o-',color=colors[m],label=names[m]);axes[1].plot([50,80,90,95],[o[f'interval_{l}_width'] for l in [50,80,90,95]],'o-',color=colors[m])
axes[0].plot([50,95],[50,95],'--',color='gray');axes[0].set(xlabel='Nominal coverage (%)',ylabel='Observed coverage (%)');axes[1].set(xlabel='Nominal coverage (%)',ylabel='Interval width (°F)');axes[0].legend(fontsize=8)
finish(fig,'interval_coverage_width','Central integer intervals · discreteness can raise coverage above nominal')
fig,axes=plt.subplots(2,3,figsize=(12,6))
for ax,m in zip(axes.flat,MODELS):
 v=H[m]['overall/ALL'];ax.bar(np.arange(10)/10+.05,v['pit'],width=.09,color=colors[m]);ax.axhline(.1,color='gray',linestyle='--');ax.set(title=names[m],xlabel='Randomized discrete PIT',ylabel='Day-weighted share',xlim=(0,1))
finish(fig,'pit','Randomized PIT · same deterministic randomization across models')
fig,axes=plt.subplots(1,2,figsize=(12,4))
for m in MODELS:
 v=H[m]['overall/ALL'];axes[0].plot(np.arange(-15,16),v['signed_error'],label=names[m],color=colors[m]);o=S[m]['overall']['ALL']['metrics'];axes[1].plot([3,5,10],[100*o[f'ae_ge_{t}'] for t in [3,5,10]],'o-',color=colors[m])
axes[0].set(xlabel='Median forecast − truth (°F)',ylabel='Day-weighted frequency');axes[1].set(xlabel='Absolute-error threshold (°F)',ylabel='Exceedance (%)');axes[0].legend(fontsize=8)
finish(fig,'signed_and_tail_errors','Signed errors and large misses · histogram endpoints include beyond ±15°F')
fig,axes=plt.subplots(2,2,figsize=(10,7))
for col,group in enumerate(['analog_kth_distance_quartile','analog_effective_sample_size_quartile']):
 values=[S['ANEN'][group].get('Q'+str(i),{}) for i in range(1,5)]
 for row,key,label,factor in [(0,'mae','MAE (°F)',1),(1,'modal_integer_hit','Exact hit (%)',100)]:
  ax=axes[row,col];ax.plot(range(1,5),[factor*v.get('metrics',{}).get(key,np.nan) for v in values],'o-',color=colors['ANEN']);ax.set(xlabel=group.replace('analog_','').replace('_',' '),ylabel=label,xticks=[1,2,3,4])
finish(fig,'analog_support_vs_error','Quartiles from selected inner forecasts at the same issue · descriptive')
for family in [k for k in S['ANEN'] if k.startswith('weather/')]:
 labels=sorted(set(S['ANEN'][family]));fig,axes=plt.subplots(1,3,figsize=(13,4))
 for ax,key,label,factor in zip(axes,['mae','modal_integer_hit','ae_ge_5'],['MAE (°F)','Exact hit (%)','Error ≥5°F (%)'],[1,100,100]):
  for m in MODELS:
   ax.plot(range(len(labels)),[factor*S[m][family][g].get('metrics',{}).get(key,np.nan) for g in labels],'o-',color=colors[m],label=names[m])
  ax.set_xticks(range(len(labels)),labels,rotation=20);ax.set_ylabel(label)
 axes[0].legend(fontsize=7)
 finish(fig,'regime_'+family.split('/')[1],family.split('/')[1]+' · training-only thresholds · forecast-state proxy')

for model in ['GAM_LS_NORMAL','GAM_LOCATION_NORMAL','GAM_LS_T5']:
 for component in ['location','scale_eta']:
  entries=[g for g in G if g['model']==model and g['component']==component];features=list(dict.fromkeys(g['feature'] for g in entries))
  if not features:continue
  fig,axes=plt.subplots(int(np.ceil(len(features)/3)),3,figsize=(13,3*int(np.ceil(len(features)/3))),squeeze=False)
  for ax,feature in zip(axes.flat,features):
   for item in entries:
    if item['feature']==feature:ax.plot(item['x'],item['effect'],label=item['outer'])
   ax.set_title(feature.replace('clock_','').replace('_',' '),fontsize=9);ax.set_xlabel('Predictor in stored model units');ax.set_ylabel('Correction (°F)' if component=='location' else 'Additive scale η');ax.legend(fontsize=7)
  for ax in list(axes.flat)[len(features):]:ax.set_visible(False)
  finish(fig,'effects_'+model+'_'+component,names[model]+' · '+component+' contributions · training ranges only · no coefficient uncertainty bands')

for model,entries in CA.items():
 for i,item in enumerate(entries):
  fig,axes=plt.subplots(2,1,figsize=(8,5),sharex=True);x=2+np.array(item['minutes'])/60
  axes[0].fill_between(x,item['lower80'],item['upper80'],alpha=.2,color=colors[model],label='80% interval');axes[0].plot(x,item['mean'],label='PMF mean',color=colors[model]);axes[0].plot(x,item['raw'],'--',color='gray',label='Raw HRRR');axes[0].axhline(item['truth'],color='black',label='Audited Tmax');axes[0].set_ylabel('Temperature (°F)');axes[0].legend(fontsize=8,ncol=2)
  axes[1].plot(x,np.array(item['probability'])*100,label='Native exact-hit confidence',color=colors[model]);axes[1].scatter(x,np.array(item['hit'])*100,s=10,label='Exact hit 0/100',color='black');axes[1].set(xlabel='Denver issue hour',ylabel='Probability / outcome (%)',xticks=[2,6,10,14,16]);axes[1].legend(fontsize=8)
  finish(fig,f'case_{model}_{i:02d}',names[model]+' · '+item['day']+' · '+item['kind']+' · ex-post illustration only')
(P/'figure_index.json').write_text(json.dumps({'figures':files,'matplotlib':matplotlib.__version__,'numpy':np.__version__},indent=2)+'\n')
print('Rendered',len(files),'figures',flush=True)
